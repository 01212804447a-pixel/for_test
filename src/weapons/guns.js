// Изогнутый магазин: от горловины вниз и вперёд
function akMag(P, mat, { steel = false } = {}) {
  const st = [];
  const N = 9;
  for (let i = 0; i <= N; i++) {
    const t = i / N;
    const a = (steel ? 0.62 : 0.5) * t;
    const L = 0.205 * t;
    // центр дуги
    const cz = 0.031 - Math.sin(a) * 0.205 * 0.5 * t * 1.6 - L * 0.12;
    const cy = -0.048 - L * 0.92;
    st.push({ p: [0, cy, cz], w: 0.0265, h: 0.068 + t * 0.012, r: 0.006, up: [0, Math.sin(a * 0.9) * 0.5, -1] });
  }
  P.add(mat, loft(st, { seg: 3 }));
  // донышко и рёбра
  const last = st[N], prev = st[N - 1];
  const T = new THREE.Vector3(...last.p).sub(new THREE.Vector3(...prev.p)).normalize();
  const e1 = new THREE.Vector3(...last.p).addScaledVector(T, -0.002), e2 = new THREE.Vector3(...last.p).addScaledVector(T, 0.007);
  P.add(mat, loft([{ p: e1.toArray(), w: 0.031, h: last.h + 0.008, r: 0.004, up: last.up }, { p: e2.toArray(), w: 0.031, h: last.h + 0.008, r: 0.004, up: last.up }]));
  if (steel) {
    for (const t of [0.25, 0.5, 0.75]) { const s = st[Math.round(t * N)]; P.add(mat, rbox(0.0285, 0.006, 0.05, 0, s.p[1], s.p[2], 0.002, { rx: -0.3 * t })); }
  } else {
    const s = st[2]; P.add(mat, rbox(0.0285, 0.005, 0.07, 0, s.p[1], s.p[2], 0.002, { rx: -0.1 }));
  }
  // зацепы
  P.add(mat, rbox(0.012, 0.008, 0.008, 0, -0.05, -0.006, 0.002));
  P.add('steelDark', rbox(0.022, 0.006, 0.05, 0, -0.046, 0.034, 0.002));
}

