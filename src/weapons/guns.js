// Модель в системе «прорезь целика» (y = 0 — линия прицеливания)
function assemble(kind, P) {
  const I = GUN_INFO[kind];
  const h = I.h, R = I.R;
  const B = new Parts(); // ось канала: y = 0
  if (kind === 'ak74' || kind === 'ak74gp' || kind === 'ak74scope' || kind === 'akm') {
    const akm = kind === 'akm';
    akReceiver(B, { akm });
    akFront(B, kind === 'ak74scope' ? 0.379 : R, kind === 'ak74scope' ? 0.062 : h, { akm });
    if (akm) akFurnitureAKM(B); else akFurnitureAK74M(B);
    const mag = B.mover('mag', [0, -0.05, 0.03]);
    akMag(mag, akm ? 'steelDark' : 'plum', { steel: akm });
    akSightBlock(B, kind === 'ak74scope' ? 0.379 : R, kind === 'ak74scope' ? 0.062 : h);
    if (kind === 'ak74gp') gp25(B);
    if (kind === 'ak74scope') { const S = B.mover('scope', [0, h, 0]); scope1P78Into(S, h); }
  } else if (kind === 'svd') {
    svd(B, h);
    const S = B.mover('scope', [0, h, 0]);
    scopeInto(S, scopePSO1, h);
  } else if (kind === 'pkm') {
    pkm(B, R, h);
  } else if (kind === 'ptrd') {
    ptrd(B, h);
  } else if (kind === 'rpg7' || kind === 'rpg7iron') {
    // для РПГ система — от оси трубы
    const t = I.muzzle;
    rpg7(B, { tx: 0, ty: 0 });
    if (kind === 'rpg7') { const S = B.mover('scope', [-t[0], -t[1], 0]); scopeInto(S, scopePGO7, 0, [-t[0], -t[1]]); }
    else rpgIron(B, { sx: -t[0], sy: -t[1], dz: 0.06 });
  } else if (kind === 'b8') binocular(B);
  else if (kind === 'grenade') grenadeF1(B);
  return B;
}

// Оптика строится относительно своей оси — переносим в систему канала
function scopeInto(S, fn, h, off = [0, h]) {
  const T = new Parts();
  fn(T);
  for (const [m, gs] of T.by) S.add(m, ...gs.map((g) => g.translate(off[0], off[1], 0)));
}
function scope1P78Into(S, h) { scopeInto(S, scope1P78, h); }

// Сдвиг в систему «прорезь целика»
function offsetFor(kind) {
  const I = GUN_INFO[kind];
  if (kind === 'rpg7') return [I.muzzle[0], I.muzzle[1], 0];
  if (kind === 'rpg7iron') return [I.muzzle[0], I.muzzle[1], -0.06];
  if (kind === 'b8' || kind === 'grenade') return [0, 0, 0];
  return [0, -I.h, 0];
}

const tpCache = new Map();
// Модель для вида от первого лица и для стенда: подвижные детали — отдельные группы
export function buildGun(kind, { shadow = false } = {}) {
  const M = gunMats();
  if (kind === 'gp25') return buildGP25View(shadow);
  const B = assemble(kind);
  const g = B.build(M, { shadow });
  const [ox, oy, oz] = offsetFor(kind);
  g.position.set(ox, oy, oz);
  const root = new THREE.Group();
  root.add(g);
  const named = g.userData.named || {};
  return { root, model: g, parts: named, info: GUN_INFO[kind] };
}

// ГП-25 при стрельбе: автомат смещён так, что квадрант — на линии прицеливания
function buildGP25View(shadow) {
  const M = gunMats();
  const B = assemble('ak74gp');
  const g = B.build(M, { shadow });
  g.position.set(0.055 - 0.0, -0.1 + 0.109 - 0.062, 0.15);
  const root = new THREE.Group();
  root.add(g);
  // прицельные элементы квадранта
  const Q = new Parts();
  for (const sx of [-1, 1]) Q.add('steel', rbox(0.0055, 0.011, 0.003, sx * 0.006, -0.0055, 0, 0.0005));
  Q.add('steel', rbox(0.0065, 0.004, 0.003, 0, -0.009, 0, 0.0005));
  Q.add('steel', rbox(0.0035, 0.013, 0.003, 0, -0.0065, -0.12, 0.0005));
  Q.add('steel', rbox(0.004, 0.006, 0.125, 0, -0.016, -0.06, 0.001));
  Q.add('steelDark', cylZ(0.009, -0.04, -0.07, { x: -0.012, y: -0.03, seg: 16 }));
  root.add(Q.build(M, { shadow }));
  return { root, model: g, parts: g.userData.named || {}, info: GUN_INFO.gp25 };
}

// Модель для бойцов (вид от третьего лица): общие геометрии, без подвижных деталей
export function thirdPersonGun(kind) {
  if (!tpCache.has(kind)) {
    const M = gunMats();
    const B = assemble(kind);
    // подвижные детали вливаем в основные
    const flat = new Parts();
    const pour = (src) => { for (const [m, gs] of src.by) flat.add(m, ...gs); for (const mv of src.movers) pour(mv); };
    pour(B);
    const g = flat.build(M, { shadow: true });
    tpCache.set(kind, g);
  }
  const src = tpCache.get(kind);
  const I = GUN_INFO[kind];
  const [ox, oy, oz] = offsetFor(kind);
  const inner = new THREE.Group();
  for (const m of src.children) { const c = new THREE.Mesh(m.geometry, m.material); c.castShadow = true; c.receiveShadow = true; inner.add(c); }
  inner.position.set(ox, oy, oz);
  const object = new THREE.Group();
  object.add(inner);
  const v = (a) => new THREE.Vector3(...a);
  return { key: kind, object, gripR: v(I.gripR), gripL: v(I.gripL), muzzle: v(I.muzzle), butt: v(I.butt || [0, -0.1, 0.4]) };
}
